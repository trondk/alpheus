// Command testlist writes docs/tests.md, the list of every automated test
// for the website, from the tests' own doc comments and the test scripts'
// headers, so the list never differs from the tests. It fails when a test
// has no doc comment, or an end-to-end testcase lacks a part of its
// description.
//
// Usage: go run ./hack/testlist > docs/tests.md
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

const module = "alpheus-dev.org/alpheus/"

// test is one Test or Fuzz function and its doc comment.
type test struct {
	name, file string
	doc        string
}

// pkg is a package with tests.
type pkg struct {
	path  string // relative to the module
	tests []test
}

// labels are the parts every end-to-end testcase describes, in order.
var labels = []string{"Flow", "What it tests", "Done to the run", "Passes when"}

// scripts are the tests that are not Go, and the make target that runs
// each.
var scripts = []struct{ file, target string }{
	{"hack/test-crd.sh", "make test-crd"},
	{"hack/test-chart.sh", "make test-chart"},
	{"templates/component-python/test.sh", "make test-templates"},
	{"examples/log-report/test.sh", "make test-templates"},
}

func main() {
	pkgs, err := packages()
	if err == nil {
		err = write(os.Stdout, pkgs)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "testlist:", err)
		os.Exit(1)
	}
}

// packages finds every package with tests and reads their doc comments.
func packages() ([]pkg, error) {
	out, err := exec.Command("go", "list", "-f", `{{.ImportPath}}|{{.Dir}}|{{join .TestGoFiles ","}}`, "./...").Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w", err)
	}
	var pkgs []pkg
	var missing []string
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		parts := strings.SplitN(line, "|", 3)
		if len(parts) != 3 || parts[2] == "" {
			continue
		}
		p := pkg{path: strings.TrimPrefix(parts[0], module)}
		for _, name := range strings.Split(parts[2], ",") {
			file := filepath.Join(parts[1], name)
			f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.ParseComments)
			if err != nil {
				return nil, err
			}
			rel := p.path + "/" + name
			for _, d := range f.Decls {
				fn, ok := d.(*ast.FuncDecl)
				if !ok || fn.Recv != nil || fn.Name.Name == "TestMain" ||
					!strings.HasPrefix(fn.Name.Name, "Test") && !strings.HasPrefix(fn.Name.Name, "Fuzz") {
					continue
				}
				if fn.Doc == nil {
					missing = append(missing, rel+": "+fn.Name.Name)
					continue
				}
				p.tests = append(p.tests, test{name: fn.Name.Name, file: rel, doc: strings.TrimSpace(fn.Doc.Text())})
			}
		}
		if len(p.tests) > 0 {
			pkgs = append(pkgs, p)
		}
	}
	if len(missing) > 0 {
		return nil, fmt.Errorf("tests without a doc comment:\n  %s", strings.Join(missing, "\n  "))
	}
	return pkgs, nil
}

// text is a doc comment's words without the function's name, starting
// with a capital.
func text(t test) string {
	doc := t.doc
	if rest, ok := strings.CutPrefix(doc, t.name+" "); ok && rest != "" {
		doc = strings.ToUpper(rest[:1]) + rest[1:]
	}
	return doc
}

var htmlish = strings.NewReplacer("<", "&lt;", ">", "&gt;", "*", `\*`)

// inline is a paragraph as one line of Markdown: no raw HTML, no stray
// emphasis.
func inline(s string) string {
	return htmlish.Replace(strings.Join(strings.Fields(s), " "))
}

// paragraphs splits a doc comment into paragraphs; a code block, indented
// in the comment, is kept with its lines.
func paragraphs(doc string) []string {
	var out []string
	for _, p := range strings.Split(doc, "\n\n") {
		if p = strings.Trim(p, "\n"); p != "" {
			out = append(out, p)
		}
	}
	return out
}

func isCode(p string) bool { return strings.HasPrefix(p, "\t") || strings.HasPrefix(p, "    ") }

var testcaseName = regexp.MustCompile(`^TestTestcase(\d+)$`)

func write(w io.Writer, pkgs []pkg) error {
	var b bytes.Buffer
	b.WriteString(`---
title: Tests
description: Every automated test of Alpheus, what it checks, and what it takes to pass, generated from the tests themselves.
weight: 40
---

<!-- Generated by make generate from the tests' doc comments; do not edit. -->

Every test below runs automatically; none is a manual check. The
descriptions come from the tests' own doc comments, so this page changes
with the tests.

A test passes when everything it checks holds. That is not always a run
that succeeds: several testcases make a run fail on purpose, and pass when
it fails in the way it should, with the right reason and nothing lost.
Their "Passes when" says so.

| How | What it runs | Needs |
|---|---|---|
| ` + "`make test`" + ` | The unit and integration tests, with the race detector | Go; envtest's API server, which the target fetches |
| ` + "`make test-s3`" + `, ` + "`make test-agent-s3`" + ` | TestS3 and TestS3Restart against a real bucket | The Vagrant test cluster's Garage |
| ` + "`make e2e`" + ` | The end-to-end testcases, after building and installing the images | The Vagrant test cluster |
| ` + "`make e2e-minio`" + ` | The same testcases against MinIO instead of Garage | The Vagrant test cluster |
| ` + "`make test-upgrade`" + ` | testcase18, an upgrade in the middle of a run | The Vagrant test cluster |
| ` + "`make test-crd`" + `, ` + "`make test-chart`" + `, ` + "`make test-templates`" + ` | The scripts under [Other tests](#other-tests) | A cluster for test-crd; podman or docker for test-templates |
| ` + "`make fuzz`" + ` | The Fuzz functions, for a while each | Go |

Each run of ` + "`make e2e`" + ` ends with a report, made by
{{< repolink "hack/report.sh" >}}, with every testcase's result, time and
output next to its description. The reports stay on the machine that ran
the tests, in ` + "`_out/reports/`" + `. The [development page](/development/)
says how to set up the test cluster.

`)
	var e2e *pkg
	for i := range pkgs {
		if pkgs[i].path == "test/e2e" {
			e2e = &pkgs[i]
		}
	}
	if e2e == nil {
		return fmt.Errorf("no tests in test/e2e")
	}
	if err := writeTestcases(&b, e2e); err != nil {
		return err
	}

	b.WriteString("## Unit and integration tests\n\n")
	b.WriteString("These run with `make test`, without a cluster. " +
		"The controller's tests run against a real API server (envtest), and the agent's run whole flows " +
		"in one process against an in-memory store.\n\n")
	for _, p := range pkgs {
		if p.path == "test/e2e" {
			continue
		}
		fmt.Fprintf(&b, "### %s\n\n", p.path)
		b.WriteString("| Test | What it checks |\n|---|---|\n")
		for _, t := range p.tests {
			var cell []string
			for _, para := range paragraphs(text(t)) {
				if isCode(para) {
					for _, l := range strings.Split(para, "\n") {
						if l = strings.TrimSpace(l); l != "" {
							cell = append(cell, "`"+l+"`")
						}
					}
					continue
				}
				cell = append(cell, inline(para))
			}
			fmt.Fprintf(&b, "| `%s` | %s |\n", t.name, strings.ReplaceAll(strings.Join(cell, " "), "|", `\|`))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Other tests\n\n")
	b.WriteString("| Script | Run by | What it checks |\n|---|---|---|\n")
	for _, s := range scripts {
		head, err := scriptHeader(s.file)
		if err != nil {
			return err
		}
		fmt.Fprintf(&b, "| {{< repolink %q >}} | `%s` | %s |\n", s.file, s.target, inline(head))
	}
	_, err := w.Write(b.Bytes())
	return err
}

// writeTestcases writes a section for each end-to-end testcase, with the
// parts of its description under their labels.
func writeTestcases(b *bytes.Buffer, p *pkg) error {
	b.WriteString("## End-to-end testcases\n\n")
	b.WriteString("Each testcase runs a flow on the two-node test cluster with Talos, " +
		"Garage as the storage and Zot as the registry, through the real controller, agents and components. " +
		"The flows are in {{< repolink \"test/e2e/testdata/\" >}}, and most use the test component in " +
		"{{< repolink \"test/components/\" >}}, whose sink checks every byte it reads.\n\n")
	var cases []test
	for _, t := range p.tests {
		if testcaseName.MatchString(t.name) {
			cases = append(cases, t)
		}
	}
	slices.SortFunc(cases, func(a, b test) int { return strings.Compare(a.name, b.name) })
	for _, t := range cases {
		n := testcaseName.FindStringSubmatch(t.name)[1]
		paras := paragraphs(text(t))
		fmt.Fprintf(b, "### testcase%s\n\n%s\n\n", n, inline(paras[0]))
		found := map[string]bool{}
		for _, para := range paras[1:] {
			if isCode(para) {
				b.WriteString("```\n")
				for _, l := range strings.Split(para, "\n") {
					b.WriteString(strings.TrimPrefix(strings.TrimPrefix(l, "\t"), "    ") + "\n")
				}
				b.WriteString("```\n\n")
				continue
			}
			label, rest, ok := strings.Cut(para, ": ")
			if ok && slices.Contains(labels, label) {
				found[label] = true
				fmt.Fprintf(b, "**%s:** %s\n\n", label, inline(rest))
				continue
			}
			fmt.Fprintf(b, "%s\n\n", inline(para))
		}
		for _, l := range labels {
			if !found[l] {
				return fmt.Errorf("%s: the doc comment has no %q paragraph", t.name, l+":")
			}
		}
		file := fmt.Sprintf("test/e2e/testdata/testcase%s.yaml", n)
		fmt.Fprintf(b, "Source: {{< repolink %q >}}", p.path+"/testcase"+n+"_test.go")
		if _, err := os.Stat(file); err == nil {
			fmt.Fprintf(b, ", flow {{< repolink %q >}}", file)
		}
		b.WriteString("\n\n")
	}
	return nil
}

// scriptHeader is a script's first comment, up to its usage.
func scriptHeader(file string) (string, error) {
	f, err := os.Open(file)
	if err != nil {
		return "", err
	}
	defer f.Close()
	var lines []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		l := sc.Text()
		if strings.HasPrefix(l, "#!") {
			continue
		}
		rest, ok := strings.CutPrefix(l, "#")
		rest = strings.TrimSpace(rest)
		if !ok || rest == "" || strings.HasPrefix(rest, "Usage") {
			break
		}
		lines = append(lines, rest)
	}
	if len(lines) == 0 {
		return "", fmt.Errorf("%s has no header comment", file)
	}
	return strings.Join(lines, " "), sc.Err()
}
